# 5. Training loop
# ================================================================

def make_batches(x, y, batch_size, shuffle=True):
    """Yield mini-batches from data."""
    N = x.shape[0]
    idx = np.arange(N)
    if shuffle:
        np.random.shuffle(idx)
    for start in range(0, N, batch_size):
        end = min(start + batch_size, N)
        batch_idx = idx[start:end]
        yield x[batch_idx], y[batch_idx]


def evaluate(model, val_x, val_y, batch_size=256):
    """Compute val loss and accuracy."""
    total_loss = 0.0
    correct = 0
    total = 0
    for bx, by in make_batches(val_x, val_y, batch_size, shuffle=False):
        logits = model.forward(bx)
        loss, _ = cross_entropy_loss(logits, by)
        total_loss += loss * by.shape[0]
        correct += (logits.argmax(axis=1) == by).sum()
        total += by.shape[0]
    return total_loss / total, correct / total


def train_one_run(config, project_name, group_name, run_idx, total_runs,
                  train_x, train_y, val_x, val_y, raw_val_images):
    """Train a single model run with full wandb integration."""

    name = config["name"]
    print("\n[Run %d/%d] %s (hidden=%s, lr=%s, act=%s)" % (
        run_idx, total_runs, name, config["hidden_sizes"],
        config["lr"], config["activation"]))
    print("-" * 60)

    os.environ["WANDB_BASE_URL"] = SERVER_URL
    os.environ["WANDB_API_KEY"] = API_KEY

    # --- wandb.init ---
    run = wandb.init(
        project=project_name,
        name=name,
        group=group_name,
        job_type="train",
        tags=config["tags"],
        notes=config["notes"],
        config=config,
    )

    epochs = config["epochs"]

    # --- Build model ---
    np.random.seed(42 + run_idx)
    model = NumpyMLP(
        hidden_sizes=config["hidden_sizes"],
        activation=config["activation"],
    )
    optimizer = Adam(model.linear_layers, lr=config["lr"])

    # --- Training ---
    t0 = time.time()
    best_val_acc = 0.0
    best_epoch = 0
    log_images_every = max(1, epochs // 5)

    for epoch in range(epochs):
        # Cosine annealing LR
        current_lr = cosine_annealing_lr(optimizer, epoch, epochs)

        # --- Train epoch ---
        train_loss_sum = 0.0
        train_correct = 0
        train_total = 0

        for bx, by in make_batches(train_x, train_y, config["batch_size"], shuffle=True):
            # Forward
            logits = model.forward(bx)
            loss, dlogits = cross_entropy_loss(logits, by)

            # Backward
            model.backward(dlogits)

            # Update
            optimizer.step()

            train_loss_sum += loss * by.shape[0]
            train_correct += (logits.argmax(axis=1) == by).sum()
            train_total += by.shape[0]

        train_loss = train_loss_sum / train_total
        train_acc = train_correct / train_total
        val_loss, val_acc = evaluate(model, val_x, val_y)

        # --- wandb.log ---
        log_dict = {
            "epoch": epoch,
            "train/loss": float(train_loss),
            "train/accuracy": float(train_acc),
            "val/loss": float(val_loss),
            "val/accuracy": float(val_acc),
            "learning_rate": float(current_lr),
        }

        # --- wandb.Image: prediction samples ---
        if epoch % log_images_every == 0 or epoch == epochs - 1:
            sample_x = val_x[:16]
            sample_logits = model.forward(sample_x)
            preds = sample_logits.argmax(axis=1)
            probs = softmax(sample_logits)
            confs = probs.max(axis=1)

            wandb_images = []
            for i in range(16):
                raw = raw_val_images[i]
                true_lbl = int(val_y[i])
                pred_lbl = int(preds[i])
                conf = float(confs[i])
                mark = "OK" if true_lbl == pred_lbl else "WRONG"
                caption = "true=%d pred=%d (%.0f%%) %s" % (true_lbl, pred_lbl, conf * 100, mark)
                wandb_images.append(wandb.Image(raw, caption=caption, mode="L"))
            log_dict["predictions"] = wandb_images

        wandb.log(log_dict)

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_epoch = epoch

        if epoch % 10 == 0 or epoch == epochs - 1:
            print("  Epoch %3d/%d | train_loss=%.4f train_acc=%.3f "
                  "| val_loss=%.4f val_acc=%.3f | lr=%.6f" % (
                      epoch + 1, epochs, train_loss, train_acc,
                      val_loss, val_acc, current_lr))

    training_time = time.time() - t0

    # --- wandb.summary ---
    wandb.summary["best_val_acc"] = float(best_val_acc)
    wandb.summary["best_val_loss"] = float(val_loss)
    wandb.summary["best_epoch"] = int(best_epoch)
    wandb.summary["training_time_sec"] = round(training_time, 2)
    wandb.summary["total_params"] = model.total_params

    print("  Done in %.1fs | best_val_acc=%.3f (epoch %d) | %d params" % (
        training_time, best_val_acc, best_epoch, model.total_params))

    # --- wandb.Table: prediction results ---
    try:
        logits = model.forward(val_x[:100])
        preds = logits.argmax(axis=1)
        probs = softmax(logits)
        confs = probs.max(axis=1)

        columns = ["image", "true", "predicted", "confidence", "correct"]
        table = wandb.Table(columns=columns)
        for i in range(100):
            img = wandb.Image(raw_val_images[i], mode="L")
            table.add_data(
                img,
                int(val_y[i]),
                int(preds[i]),
                round(float(confs[i]), 4),
                int(preds[i]) == int(val_y[i]),
            )
        wandb.log({"prediction_table": table})
        print("  Logged prediction table (100 samples)")
    except Exception as e:
        print("  Table logging skipped: %s" % e)

    # --- wandb.Artifact: model weights (.npz) ---
    try:
        weights_path = "model_%s.npz" % name
        np.savez(weights_path, **model.get_weights())
        artifact = wandb.Artifact(
            name="model-%s" % name,
            type="model",
            description="MNIST MLP %s (val_acc=%.3f) [pure NumPy]" % (name, best_val_acc),
            metadata={
                "architecture": str(config["hidden_sizes"]),
                "activation": config["activation"],
                "total_params": model.total_params,
                "framework": "numpy",
            },
        )
        artifact.add_file(weights_path)
        run.log_artifact(artifact)
        print("  Logged artifact: model-%s" % name)
        try:
            os.remove(weights_path)
        except OSError:
            pass
    except Exception as e:
        print("  Artifact logging skipped: %s" % e)

    wandb.finish()


