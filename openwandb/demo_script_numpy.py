# 4. MLP Model (pure NumPy)
# ================================================================

class NumpyMLP:
    """Multi-Layer Perceptron — 100% NumPy, zero frameworks."""

    def __init__(self, hidden_sizes=(128, 64), activation="relu"):
        act_map = {"relu": ReLU, "tanh": Tanh, "leaky_relu": LeakyReLU}
        act_cls = act_map.get(activation, ReLU)

        self.layers = []          # all layers (Linear + Activation)
        self.linear_layers = []   # only Linear layers (for optimizer)

        in_dim = 784
        for h in hidden_sizes:
            linear = Linear(in_dim, h)
            self.layers.append(linear)
            self.linear_layers.append(linear)
            self.layers.append(act_cls())
            in_dim = h

        # Output layer (no activation — logits)
        output = Linear(in_dim, 10)
        self.layers.append(output)
        self.linear_layers.append(output)

    def forward(self, x):
        """Forward pass through all layers."""
        out = x
        for layer in self.layers:
            out = layer.forward(out)
        return out

    def backward(self, dout):
        """Backward pass — propagate gradients through all layers in reverse."""
        for layer in reversed(self.layers):
            dout = layer.backward(dout)

    @property
    def total_params(self):
        return sum(l.num_params for l in self.linear_layers)

    def get_weights(self):
        """Export all weights as a dict (for saving)."""
        weights = {}
        for i, layer in enumerate(self.linear_layers):
            weights["W%d" % i] = layer.W.copy()
            weights["b%d" % i] = layer.b.copy()
        return weights


