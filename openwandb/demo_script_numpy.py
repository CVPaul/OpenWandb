class Adam:
    """Adam optimizer — hand-written, no frameworks."""

    def __init__(self, linear_layers, lr=0.001, beta1=0.9, beta2=0.999, eps=1e-8):
        self.layers = linear_layers
        self.lr = lr
        self.base_lr = lr
        self.beta1 = beta1
        self.beta2 = beta2
        self.eps = eps
        self.t = 0
        # Per-parameter first & second moments
        self.states = []
        for layer in self.layers:
            self.states.append({
                "mW": np.zeros_like(layer.W),
                "vW": np.zeros_like(layer.W),
                "mb": np.zeros_like(layer.b),
                "vb": np.zeros_like(layer.b),
            })

    def step(self):
        self.t += 1
        bc1 = 1.0 - self.beta1 ** self.t
        bc2 = 1.0 - self.beta2 ** self.t

        for layer, state in zip(self.layers, self.states):
            # Update W
            state["mW"] = self.beta1 * state["mW"] + (1 - self.beta1) * layer.dW
            state["vW"] = self.beta2 * state["vW"] + (1 - self.beta2) * (layer.dW ** 2)
            mW_hat = state["mW"] / bc1
            vW_hat = state["vW"] / bc2
            layer.W -= self.lr * mW_hat / (np.sqrt(vW_hat) + self.eps)

            # Update b
            state["mb"] = self.beta1 * state["mb"] + (1 - self.beta1) * layer.db
            state["vb"] = self.beta2 * state["vb"] + (1 - self.beta2) * (layer.db ** 2)
            mb_hat = state["mb"] / bc1
            vb_hat = state["vb"] / bc2
            layer.b -= self.lr * mb_hat / (np.sqrt(vb_hat) + self.eps)


def cosine_annealing_lr(optimizer, epoch, total_epochs):
    """Cosine annealing LR schedule."""
    optimizer.lr = optimizer.base_lr * 0.5 * (1 + math.cos(math.pi * epoch / total_epochs))
    return optimizer.lr


