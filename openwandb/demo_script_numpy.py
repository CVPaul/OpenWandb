# 1. Layers — forward & backward (pure NumPy)
# ================================================================

class Linear:
    """Fully connected layer: y = x @ W + b"""

    def __init__(self, in_dim, out_dim):
        # He initialization
        self.W = np.random.randn(in_dim, out_dim).astype(np.float32) * np.sqrt(2.0 / in_dim)
        self.b = np.zeros(out_dim, dtype=np.float32)
        self.dW = None
        self.db = None
        self._x = None

    def forward(self, x):
        self._x = x
        return x @ self.W + self.b

    def backward(self, dout):
        self.dW = self._x.T @ dout
        self.db = dout.sum(axis=0)
        return dout @ self.W.T

    @property
    def num_params(self):
        return self.W.size + self.b.size


class ReLU:
    """ReLU activation: max(0, x)"""
    def forward(self, x):
        self._mask = (x > 0).astype(np.float32)
        return x * self._mask

    def backward(self, dout):
        return dout * self._mask


class Tanh:
    """Tanh activation"""
    def forward(self, x):
        self._out = np.tanh(x)
        return self._out

    def backward(self, dout):
        return dout * (1.0 - self._out ** 2)


class LeakyReLU:
    """Leaky ReLU activation: x if x>0 else alpha*x"""
    def __init__(self, alpha=0.01):
        self.alpha = alpha

    def forward(self, x):
        self._pos = (x > 0).astype(np.float32)
        return x * self._pos + self.alpha * x * (1.0 - self._pos)

    def backward(self, dout):
        return dout * (self._pos + self.alpha * (1.0 - self._pos))


