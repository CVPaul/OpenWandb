def train_one_run(config, project_name, group_name, run_idx, total_runs,
                  train_x, train_y, val_x, val_y, raw_val_images):
    """Train a single model run with full wandb integration."""

    name = config["name"]
    print("\n[Run %d/%d] %s (hidden=%s, lr=%s, act=%s)" % (
        run_idx, total_runs, name, config["hidden_sizes"],
        config["lr"], config["activation"]))
    print("-" * 60)

    # --- wandb Logger ---
    os.environ["WANDB_BASE_URL"] = SERVER_URL
    os.environ["WANDB_API_KEY"] = API_KEY

    wandb_logger = WandbLogger(
        project=project_name,
        name=name,
        group=group_name,
        job_type="train",
        tags=config["tags"],
        notes=config["notes"],
        config=config,
    )

    # --- DataLoaders ---
    train_ds = TensorDataset(train_x, train_y)
    val_ds = TensorDataset(val_x, val_y)
    train_loader = DataLoader(train_ds, batch_size=config["batch_size"],
                              shuffle=True, num_workers=0)
    val_loader = DataLoader(val_ds, batch_size=256, num_workers=0)

    # --- Model ---
    model = MNISTClassifier(
        hidden_sizes=config["hidden_sizes"],
        lr=config["lr"],
        activation=config["activation"],
    )

    # --- Image prediction callback ---
    img_callback = ImagePredictionLogger(
        val_images=val_x[:16],
        val_labels=val_y[:16],
        raw_images=raw_val_images[:16],
        every_n_epochs=max(1, config["epochs"] // 5),
        num_samples=16,
    )

    # --- Train ---
    t0 = time.time()
    trainer = L.Trainer(
        max_epochs=config["epochs"],
        logger=wandb_logger,
        callbacks=[img_callback],
        enable_progress_bar=True,
        enable_checkpointing=False,
        accelerator="cpu",
        log_every_n_steps=1,
    )
    trainer.fit(model, train_loader, val_loader)
    training_time = time.time() - t0

    # --- wandb.summary ---
    metrics = trainer.callback_metrics
    wandb.summary["best_val_acc"] = metrics.get("val/accuracy", torch.tensor(0)).item()
    wandb.summary["best_val_loss"] = metrics.get("val/loss", torch.tensor(0)).item()
    wandb.summary["training_time_sec"] = round(training_time, 2)
    total_params = sum(p.numel() for p in model.parameters())
    wandb.summary["total_params"] = total_params

    print("  Done in %.1fs | val_acc=%.3f | %d params" % (
        training_time,
        metrics.get("val/accuracy", torch.tensor(0)).item(),
        total_params))

    # --- wandb.Table: prediction results ---
    try:
        model.eval()
        with torch.no_grad():
            logits = model(val_x[:100])
        preds = logits.argmax(1)
        confs = F.softmax(logits, dim=1).max(1).values

        columns = ["image", "true", "predicted", "confidence", "correct"]
        table = wandb.Table(columns=columns)
        for i in range(100):
            img = wandb.Image(raw_val_images[i], mode="L")
            table.add_data(
                img,
                int(val_y[i].item()),
                int(preds[i].item()),
                round(confs[i].item(), 4),
                preds[i].item() == val_y[i].item(),
            )
        wandb.log({"prediction_table": table})
        print("  Logged prediction table (100 samples)")
    except Exception as e:
        print("  Table logging skipped: %s" % e)

    # --- wandb.Artifact: model weights ---
    try:
        weights_path = "model_%s.pt" % name
        torch.save(model.state_dict(), weights_path)
        artifact = wandb.Artifact(
            name="model-%s" % name,
            type="model",
            description="MNIST MLP %s (val_acc=%.3f)" % (
                name, metrics.get("val/accuracy", torch.tensor(0)).item()),
            metadata={
                "architecture": str(config["hidden_sizes"]),
                "activation": config["activation"],
                "total_params": total_params,
            },
        )
        artifact.add_file(weights_path)
        wandb_logger.experiment.log_artifact(artifact)
        print("  Logged artifact: model-%s" % name)
        try:
            os.remove(weights_path)
        except OSError:
            pass
    except Exception as e:
        print("  Artifact logging skipped: %s" % e)

    wandb.finish()


