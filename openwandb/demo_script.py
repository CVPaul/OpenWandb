class ImagePredictionLogger(Callback):
    """Log sample prediction images every N epochs."""

    def __init__(self, val_images, val_labels, raw_images, every_n_epochs=5, num_samples=16):
        super().__init__()
        self.val_images = val_images      # tensor (N, 1, 28, 28) normalized
        self.val_labels = val_labels      # tensor (N,)
        self.raw_images = raw_images      # numpy uint8 (N, 28, 28) for display
        self.every_n = every_n_epochs
        self.num = num_samples

    def on_validation_epoch_end(self, trainer, pl_module):
        epoch = trainer.current_epoch
        if epoch % self.every_n != 0 and epoch != trainer.max_epochs - 1:
            return

        imgs = self.val_images[:self.num].to(pl_module.device)
        labels = self.val_labels[:self.num]
        with torch.no_grad():
            logits = pl_module(imgs)
        preds = logits.argmax(1).cpu()
        confs = F.softmax(logits, dim=1).max(1).values.cpu()

        wandb_images = []
        for i in range(self.num):
            raw = self.raw_images[i]  # uint8 28x28
            true_lbl = labels[i].item()
            pred_lbl = preds[i].item()
            conf = confs[i].item()
            mark = "OK" if true_lbl == pred_lbl else "WRONG"
            caption = "true=%d pred=%d (%.0f%%) %s" % (true_lbl, pred_lbl, conf * 100, mark)
            wandb_images.append(wandb.Image(raw, caption=caption, mode="L"))

        trainer.logger.experiment.log({"predictions": wandb_images})


