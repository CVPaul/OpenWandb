def _check_server(url, timeout=5):
    """Check if the OpenWandb server is reachable. Exit early instead of SDK retry loop."""
    import urllib.request
    import urllib.error
    check_url = url.rstrip("/") + "/graphql"
    try:
        req = urllib.request.Request(check_url, method="GET")
        urllib.request.urlopen(req, timeout=timeout)
        return True
    except (urllib.error.URLError, urllib.error.HTTPError, OSError):
        return False


def main():
    os.environ.setdefault("WANDB_BASE_URL", SERVER_URL)
    os.environ.setdefault("WANDB_API_KEY", API_KEY)
    # Prevent SDK from retrying forever if server goes down mid-run
    os.environ.setdefault("WANDB_INIT_TIMEOUT", "30")

    # --- Server connectivity check ---
    print("\nChecking OpenWandb server at %s ..." % SERVER_URL)
    if not _check_server(SERVER_URL):
        print("\n  ERROR: Cannot connect to OpenWandb server at %s" % SERVER_URL)
        print()
        print("  Please make sure the server is running:")
        print("    openwandb serve")
        print()
        print("  Or specify a different server URL:")
        print("    export WANDB_BASE_URL=http://your-server:8080")
        print("    python openwandb-demo.py")
        print()
        sys.exit(1)
    print("  Server is reachable.")

    group_name = "mnist-demo-%s" % time.strftime("%Y%m%d-%H%M%S")

    # --- Load MNIST ---
    print("\nLoading MNIST data...")
    train_images, train_labels, test_images, test_labels = load_mnist()
    print("  Train: %d images, Test: %d images" % (len(train_images), len(test_images)))

    # Prepare tensors
    train_x = torch.FloatTensor(train_images.reshape(-1, 1, 28, 28)) / 255.0
    train_y = torch.LongTensor(train_labels.astype(int))
    val_x = torch.FloatTensor(test_images.reshape(-1, 1, 28, 28)) / 255.0
    val_y = torch.LongTensor(test_labels.astype(int))

    print()
    print("=" * 60)
    print("  OpenWandb Demo - MNIST Digit Classification")
    print("  PyTorch Lightning + wandb SDK")
    print("=" * 60)
    print("  Server:     %s" % SERVER_URL)
    print("  Project:    %s" % PROJECT)
    print("  Runs:       %d" % NUM_RUNS)
    print("  Epochs:     %d" % EPOCHS)
    print("  Group:      %s" % group_name)
    print("  Dataset:    %d train / %d test" % (len(train_images), len(test_images)))
    print("  Features:   wandb.log, wandb.Image, wandb.Table, wandb.Artifact")
    print("=" * 60)

    configs = get_run_configs(NUM_RUNS, EPOCHS)
    t_start = time.time()

    for idx, cfg in enumerate(configs, 1):
        train_one_run(
            cfg, PROJECT, group_name, idx, len(configs),
            train_x, train_y, val_x, val_y,
            test_images,  # raw uint8 for wandb.Image
        )

    total_time = time.time() - t_start

    print()
    print("=" * 60)
    print("  Demo complete! (%.1fs total)" % total_time)
    print()
