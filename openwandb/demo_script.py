    print("    - Charts tab:  loss & accuracy curves")
    print("    - Media tab:   prediction images with labels")
    print("    - Config tab:  hyperparameter comparison")
    print("    - Compare all runs side-by-side")
    print()
    print("  Re-run:  python openwandb-demo.py")
    print("=" * 60)
    print()


